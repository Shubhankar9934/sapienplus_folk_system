"""Culture-first profile models (the public, human-readable contract).

These models carry the *culture-first* output of the pipeline: a visible
Cultural Fingerprint (the four D1-D4 scores + plain readings), dynamic
model-named Cultural Themes whose observations are each grounded in evidence
``claim_ids``, grounded historical drivers, competing forces, relative-to-
neighbour insights, and reasoning-first council views.

Integrity rules enforced elsewhere (engine + deterministic assembly):
- every ``Observation`` / ``HistoricalDriver`` carries the ``claim_ids`` it was
  drawn from; ungrounded items are dropped by the grounding filter.
- ``sources_count`` (per item) and ``CulturalTheme.confidence`` (per theme) are
  computed deterministically, never invented by the model.
- snapshot readings, council views, and regional distinctiveness are assembled
  deterministically from existing structured data.
"""

from __future__ import annotations

from typing import ClassVar

from pydantic import BaseModel, Field, model_validator

from folk.models.enums import Dimension


def _as_str_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [value]
    if isinstance(value, (list, tuple, set)):
        return [str(v) for v in value if v is not None and str(v).strip()]
    return [str(value)]


class Observation(BaseModel):
    """One short, concrete, lived-experience statement grounded in evidence."""

    text: str = ""
    claim_ids: list[str] = Field(default_factory=list)
    sources_count: int = 0

    @model_validator(mode="before")
    @classmethod
    def _coalesce(cls, data):
        if isinstance(data, str):
            return {"text": data}
        if isinstance(data, dict):
            if not data.get("text"):
                for k in ("text", "observation", "statement", "insight", "point"):
                    if data.get(k):
                        data["text"] = str(data[k])
                        break
            for k in ("claim_ids", "claims", "claim_id", "evidence", "sources"):
                if data.get(k) is not None:
                    data["claim_ids"] = _as_str_list(data[k])
                    break
        return data


