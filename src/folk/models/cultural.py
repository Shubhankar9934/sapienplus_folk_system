# Human-readable confidence bands. The UI shows these labels primarily; the
# raw 0-100 numbers stay available for sorting/tooltips.
CONFIDENCE_BANDS: tuple[tuple[int, str], ...] = (
    (85, "Very High"),
    (70, "High"),
    (50, "Moderate"),
    (30, "Low"),
    (0, "Contested"),
)


def confidence_label(score: int | float | None) -> str:
    """Map a 0-100 confidence score onto a band label.

    Contested (<30) / Low (<50) / Moderate (<70) / High (<85) / Very High (>=85).
    """
    if score is None:
        return "Contested"
    s = int(round(float(score)))
    for threshold, label in CONFIDENCE_BANDS:
        if s >= threshold:
            return label
    return "Contested"


class ThemeConfidence(BaseModel):
    """Transparent, three-part confidence for a theme (each 0-100) plus labels.

    Computed deterministically by the grounding filter, never invented:
    - ``evidence_strength``: how many distinct claims/sources/specialists back it.
    - ``expert_agreement``: how much the specialist seats agreed on the theme's
      dominant dimension.
    - ``framework_agreement``: cross-framework agreement on that dimension.

    The ``*_label`` fields are derived from the numbers (Contested / Low /
    Moderate / High / Very High) and are what the UI shows primarily.
    """

    evidence_strength: int = 0
    expert_agreement: int = 0
    framework_agreement: int = 0
    evidence_strength_label: str = ""
    expert_agreement_label: str = ""
    framework_agreement_label: str = ""
    # One-sentence, deterministically-composed "why this confidence" narrative
    # (computed by the engine, never invented by the model).
    confidence_explanation: str = ""

    @model_validator(mode="after")
    def _labels(self) -> "ThemeConfidence":
        self.evidence_strength_label = confidence_label(self.evidence_strength)
        self.expert_agreement_label = confidence_label(self.expert_agreement)
        self.framework_agreement_label = confidence_label(self.framework_agreement)
        return self


class CulturalTheme(BaseModel):
    """A dynamic, model-named cultural theme (e.g. 'Rules & Order', 'Nomadic
    Heritage') clustering grounded observations.

    ``title`` is generated by the model from the evidence (not a fixed bucket).
    ``confidence`` (a transparent three-part breakdown) and ``sources_count`` are
    computed deterministically by the grounding filter from how many distinct
    claims/sources/specialists back the theme, and drive the UI's
    Strong/Moderate/Emerging rating + sort.
    """

    title: str = ""
    confidence: ThemeConfidence = Field(default_factory=ThemeConfidence)
    sources_count: int = 0
    observations: list[Observation] = Field(default_factory=list)
    historical_roots: list[HistoricalDriver] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def _coalesce(cls, data):
        if isinstance(data, dict):
            if not data.get("title"):
                for k in ("title", "name", "theme", "label"):
                    if data.get(k):
                        data["title"] = str(data[k])
                        break
            if data.get("observations") is None:
                for k in ("observations", "bullets", "points", "items"):
                    if data.get(k) is not None:
                        data["observations"] = data[k]
                        break
            # The model may emit a bare numeric confidence; coerce to the
            # breakdown shape (the grounding filter recomputes it regardless).
            conf = data.get("confidence")
            if isinstance(conf, (int, float)):
                data["confidence"] = {"evidence_strength": int(conf)}
        return data


